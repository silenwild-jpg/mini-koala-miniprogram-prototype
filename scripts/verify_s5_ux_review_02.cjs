'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const root='app/prototype/parallel/core-journey-fix-01/demo/br04/';
const html=fs.readFileSync(root+'s5/index.html','utf8');
const css=fs.readFileSync(root+'s5/style.css','utf8');
const js=fs.readFileSync(root+'bridge.js','utf8');
assert.match(html,/id="s5-advisor"[^>]+hidden/);
assert.match(html,/id="s5-advisor-action"/);
assert.match(html,/class="major-unit s5-store-card"/);
assert.match(html,/class="minor-unit s5-store-card"/);
assert.doesNotMatch(html,/class="(?:fixed-buy|fixed-cta|bottom-buy|sticky-checkout)"/);
assert.match(css,/\.s5-advisor\[hidden\]\{display:none!important\}/);
assert.match(css,/data-advisor-visible="true"/);
assert.ok(js.includes('emptyEstoreTop+176'),'compact empty/incomplete layout contract');
assert.ok(js.includes("sizes.reduce((a,b)=>a+b,0)"),'same-size store-card dynamic page height');
assert.ok(js.includes("Number(item.volume)<Number(core.state().requirement.capacity_m3)"),'undersized alternative cannot directly order');
assert.match(js,/\$\('s5-advisor-action'\)\.onclick=\(\)=>consult\('advisor'\)/);
const start=js.indexOf('function s5MatchState(');
const end=js.indexOf('function renderS5()',start);
assert.ok(start>0&&end>start,'state helpers exist');
const ctx={core:{amounts:ids=>({rent_total:ids[0]})},Number};
vm.createContext(ctx);
vm.runInContext(js.slice(start,end),ctx);
const rows=(volume,rent,other={})=>[{volume,ids:[rent],...other}];
const req=(capacity,confirmed=true)=>({capacity_m3:capacity,term_confirmed:confirmed});
const status=(r,v)=>ctx.s5MatchState(r,v);
assert.equal(status(rows(3,2000),req(3)),'matched');
assert.equal(status(rows(3,2000),req(4)),'near');
assert.equal(status(rows(3,2000,{expandedSearch:true}),req(3)),'expanded');
assert.equal(status(rows(15,2000,{combo:true}),req(15)),'combo');
assert.equal(status(rows(60,2000),req(60)),'large');
assert.equal(status([],req(3)),'none');
assert.equal(status(rows(3,2000),req(3,false)),'incomplete');
assert.equal(ctx.s5AdvisorNeeded(rows(3,2000),req(3)),false);
assert.equal(ctx.s5AdvisorNeeded(rows(3,2001),req(3)),true);
assert.equal(ctx.s5AdvisorNeeded(rows(10,1800),req(10)),false);
assert.equal(ctx.s5AdvisorNeeded(rows(11,1800),req(11)),true);
assert.equal(ctx.s5AdvisorNeeded([],req(11)),true);
for(const width of [375,390]){
 const scale=width/371;
 assert.ok(scale>=1&&scale<1.06);
 assert.match(css,/\.s5-store-address/);
 assert.match(css,/\.s5-unit-row/);
}
console.log('S5 UX REVIEW 02: static state contract, threshold boundaries and new store parity layout contract PASS (not browser screenshots)');
