'use strict';
const assert=require('node:assert/strict');
const F=require('../app/prototype/parallel/core-journey-fix-01/demo/fixtures.js');
const config=require('../app/prototype/parallel/core-journey-fix-01/demo/br03-demo-snapshots.js');
const {create}=require('../app/prototype/parallel/core-journey-fix-01/demo/promotion-policy.js');
const policy=create({fixture:F,config});
const campaign=config.campaigns.find(x=>x.unitId==='SIM_BJ01_U04');
const unit=F.units.find(x=>x.id==='SIM_BJ01_U04');
const store=F.stores.find(x=>x.id==='SIM_BJ01');
assert(policy.evaluateCampaign(campaign,{unit,store,available:true,termMonths:6}).eligible);
assert.equal(policy.evaluateCampaign(campaign,{unit,store,available:true,termMonths:3}).status,'INELIGIBLE');
assert(policy.evaluateCampaign({...campaign,until:'2020-01-01'},{unit,store,available:true,termMonths:6}).reasons.includes('ENDED'));
assert(policy.evaluateCampaign(campaign,{unit:{...unit,revision:99},store,available:true,termMonths:6}).reasons.includes('CATALOG_REVISION_MISMATCH'));
assert.equal(policy.stacking('TERM_DISCOUNT','RENT_CASH_COUPON').status,'ALLOWED');
assert.equal(policy.stacking('TERM_DISCOUNT','MOVING_SERVICE').status,'ALLOWED');
assert.equal(policy.stacking('RENT_CASH_COUPON','MOVING_SERVICE').status,'ALLOWED');
assert.equal(policy.stacking('UNIT_SPECIAL_PRICE','TERM_DISCOUNT').status,'NEEDS_CONFIRMATION');
assert.equal(policy.stacking('UNIT_SPECIAL_PRICE','RENT_CASH_COUPON').status,'NEEDS_CONFIRMATION');
assert.equal(policy.stacking('CAMPAIGN_FREE_TERM','TERM_DISCOUNT').status,'NEEDS_CONFIRMATION');
assert.equal(policy.stacking('SALES_FREE_TERM','RENT_CASH_COUPON').status,'NEEDS_CONFIRMATION');
let c={id:'C1',status:'AVAILABLE'};
c=policy.transitionCoupon(c,'SELECTED');
c=policy.transitionCoupon(c,'LOCKED');
c=policy.transitionCoupon(c,'AVAILABLE');
c=policy.transitionCoupon(c,'SELECTED');
c=policy.transitionCoupon(c,'LOCKED');
c=policy.transitionCoupon(c,'REDEEMED');
assert.equal(c.status,'REDEEMED');
assert.throws(()=>policy.transitionCoupon(c,'AVAILABLE'),/INVALID_COUPON_TRANSITION/);
assert.throws(()=>policy.transitionCoupon({id:'C2',status:'REDEEMED'},'LOCKED'),/INVALID_COUPON_TRANSITION/);
console.log('PROMO-ENTITLEMENT-MODEL-01 PASS: campaign scope, date, term, revision, stacking and coupon lifecycle');
