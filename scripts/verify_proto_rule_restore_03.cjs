#!/usr/bin/env node
'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),demo=path.join(root,'app/prototype/parallel/core-journey-fix-01/demo');
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const app=read('app/prototype/parallel/core-journey-fix-01/demo/app.js');
const live=read('app/prototype/parallel/core-journey-fix-01/demo/s01-r2-live.html');
const align=read('app/prototype/parallel/core-journey-fix-01/demo/visual-align.css');
const binder=read('app/prototype/parallel/core-journey-fix-01/demo/s01-r2-bind.js');
const contract=read('app/prototype/parallel/core-journey-fix-01/demo/central-contract.js');
const build=read('scripts/build_rc2_isolated_demo.py');
const section=live.match(/<section class="filters"[^>]*>([\s\S]*?)<\/section>/);
assert(section,'R2 filters section missing');
const items=[...section[1].matchAll(/<div class="filter">\s*([^<]+)\s*<span/g)].map(x=>x[1].trim());
assert.deepEqual(items,['排序','距离','服务'],'R2 filter order');
assert.match(live,/grid-template-columns:repeat\(3,minmax\(0,1fr\)\)/,'R2 grid should use three columns');
assert.match(align,/\.page-S01 \.filter-bar\{[^}]*grid-template-columns:repeat\(3,minmax\(0,1fr\)\)/,'default S01 grid');
assert.equal((app.match(/class="filter-btn /g)||[]).length,3,'default S01 should render three buttons');
assert.match(app,/data-action="serviceFilter">服务/,'default third filter should be services');
assert.doesNotMatch(app,/data-action="priceFilter"|setPrice\(v\)|handlers\.priceFilter/,'retired price filtering still reachable');
assert.match(app,/if\(visual\.price!=='all'\)\{visual\.price='all';saveVisual\(\);\}/,'stale hidden price state not migrated');
assert.match(app,/filter\(index\)\{if\(!\[0,1,2\]\.includes\(index\)\)return;/,'R2 0/1/2 mappings not frozen');
assert.match(app,/filterLabels:\[visual\.sort.*visual\.service.*\],filterActive:\[visual\.sort.*visual\.service/,'R2 three labels/active flags');
assert.match(binder,/document\.querySelectorAll\('\.filter'\)\.forEach\(\(n,i\)=>/,'binder must assign indexes dynamically');
assert(!/U01\s*:/.test(contract),'U01 may not be a central route');
assert.match(contract,/DIRECT_ORDER_NOT_ALLOWED/,'order direct-entry guard lost');
assert.match(app,/function unitRow\(u\).*?data-action="choose"/,'S02 unit purchase path missing');
assert.match(app,/openStore\(id,from\).*?go\('S02',id\)/,'S02 route from recommendation missing');
assert(!fs.readdirSync(demo).some(n=>/u01.*\.html$/i.test(n)),'U01 page reintroduced in live runtime');
assert.match(build,/U01_RETIRED_PAGE_BUNDLED/,'U01 exclusion gate missing');
const result={status:'PROTO_RULE_RESTORE_03_STATIC_PASS',s01_filters:items,default_s01_filters:3,u01_central_route:false,u01_runtime_html:false,original_archival_pages_unchanged:true,release_gate:'HOLD'};
const out=path.join(root,'release-evidence/rule-restore-03');fs.mkdirSync(out,{recursive:true});fs.writeFileSync(path.join(out,'static-check.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));
