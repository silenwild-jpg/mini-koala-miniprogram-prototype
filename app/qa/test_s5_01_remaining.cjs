const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const read=name=>fs.readFileSync(path.join(root,'prototype',name),'utf8');
const profiles=['near','short','large'].map((store_id,i)=>({store_id,store_name:store_id,city:'北京市',district:'朝阳区',address:'demo '+i}));
const units={near:[{id:'n',v:4.4,base:100,available_count:1}],short:[{id:'s',v:4.9,base:120,available_count:1}],large:[{id:'l',v:5.4,base:130,available_count:1}]};
const storeId=id=>profiles.find(profile=>profile.store_id===id);
const context={window:{MINI_KOALA_DATA:{getStoresByCity:city=>city==='北京市'?profiles:[],getStore:storeId,getLegacyUnits:id=>units[id]||[],resolveStoreId:id=>id},MINI_STORAGE_MASTER_V222:{route_base:{guomao:{near:{drive:[8,1]},short:{drive:[12,2]},large:{drive:[20,6]}}}}}};
vm.runInNewContext(read('mini_koala_recommendation_policy_v2.js'),context);
vm.runInNewContext(read('mini_storage_requirement_recommendation_v274.js'),context);
const api=context.window.MINI_STORAGE_REQUIREMENT_RECOMMENDATION_V274;
assert.equal(api.isReasonableAlternative(4.9,5),true,'0.1 m3 shortage is a near alternative');
assert.equal(api.isReasonableAlternative(1,5),false,'very small unit cannot be called near');
assert.equal(api.hasTrustedLargeItem([{risk_level:'large',dimension_status:'unknown',dims_m:[2,1,1]}]),false);
assert.equal(api.hasTrustedLargeItem([{risk_level:'large',dimension_status:'measured',dims_m:[2,1,1]}]),true);
let result=api.recommend({min:5,max:5.1,target:5,term:6});
assert.equal(result.fallback,true);
assert.equal(result.rows[0].storeId,'short','nearest capacity gap ranks ahead of route distance');
assert.equal((5-result.rows[0].unit.v).toFixed(1),'0.1');
units.near[0].available_count=0;units.short[0].available_count=0;units.large[0].available_count=0;
result=api.recommend({min:5,max:5.1,target:5,term:6});
assert.equal(result.rows.length,0,'zero rentable inventory produces a real empty state');
const s5=read('space_decision_assistant_v4_5_23_self_service_synced_Visual_V2_7_4.html');
assert.match(s5,/recommendationSet\.fallback\?\{rows:recommendationSet\.rows,highlights:\{\}\}/,'fallback cards preserve the capacity-gap order');
assert.match(s5,/x\.matchType==='combo'&&hasTrustedLargeItem/);
assert.match(s5,/组合仓由多个独立仓位组成，大件物品请先确认能否放入其中一间。/);
assert.doesNotMatch(s5,/容量匹配当前需求范围，可查看具体仓位确认存放条件。/);
assert.match(s5,/容量接近的备选方案/);
console.log('PASS S5 capacity-gap alternatives, zero stock, and trusted-large combo explanation');
